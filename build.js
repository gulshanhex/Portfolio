#!/usr/bin/env node
/**
 * GK Portfolio — Build Script
 * Produces bundled_worker.js: a single file ready to paste into Cloudflare Worker editor.
 *
 * Usage:  node build.js
 * Output: bundled_worker.js
 *
 * What it does:
 *  1. Reads src/templates/css.js    → extracts BASE_CSS + FONTS constants
 *  2. Reads src/templates/public.js → extracts renderPublicPage + render404Page
 *  3. Reads src/templates/admin.js  → extracts renderLoginPage + renderAdminPanel
 *  4. Reads src/templates/docs.js   → extracts renderDocsPage
 *  5. Reads worker.js               → strips stub section (between @@STUB_START/@@STUB_END)
 *                                     and renames stub calls to real function names
 *  6. Writes bundled_worker.js      → paste-ready single file
 */

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const OUT  = path.join(ROOT, 'bundled_worker.js');

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

// ── Read source files ─────────────────────────────────────────────────────
const cssSource    = read('src/templates/css.js');
const publicSource = read('src/templates/public.js');
const adminSource  = read('src/templates/admin.js');
const docsSource   = read('src/templates/docs.js');
const workerSource = read('worker.js');

// ── Strip module boilerplate from template files ──────────────────────────
// Remove: import statements, export keywords
function stripModuleBoilerplate(src) {
  return src
    // Remove import lines
    .replace(/^import\s+.*?from\s+['"][^'"]+['"]\s*;?\s*\n/gm, '')
    // Strip 'export' from function/const/class declarations
    .replace(/^export\s+(function|const|class|async\s+function)\s+/gm, '$1 ')
    .replace(/^export\s+default\s+/gm, 'const _default = ')
    .trim();
}

const cssBlock    = stripModuleBoilerplate(cssSource);
const publicBlock = stripModuleBoilerplate(publicSource);
const adminBlock  = stripModuleBoilerplate(adminSource);
const docsBlock   = stripModuleBoilerplate(docsSource);

// ── Process worker.js ─────────────────────────────────────────────────────

// Step 1: Remove the stub section (between sentinel comments, inclusive)
let workerBody = workerSource;

const stubStart = '// @@STUB_START';
const stubEnd   = '// @@STUB_END';
const startIdx  = workerBody.indexOf(stubStart);
const endIdx    = workerBody.indexOf(stubEnd);

if (startIdx === -1 || endIdx === -1) {
  console.error('ERROR: Could not find @@STUB_START / @@STUB_END sentinels in worker.js');
  process.exit(1);
}

// Remove from @@STUB_START to end of @@STUB_END line (inclusive)
const endOfStubLine = workerBody.indexOf('\n', endIdx);
workerBody = workerBody.slice(0, startIdx).trimEnd() + '\n' +
             workerBody.slice(endOfStubLine + 1);

// Step 2: Remove import statements at top (if any remain)
workerBody = workerBody.replace(/^import\s+.*?from\s+['"][^'"]+['"]\s*;?\s*\n/gm, '');

// Step 3: The worker.js uses short stub call names; rename them to match
// the real exported function names from the template files.
// renderPublic(...)       → renderPublicPage(...)
// renderLogin(...)        → renderLoginPage(...)
// renderAdminPanel(...)   → stays as renderAdminPanel(...) (same name in both)
// renderDocs(...)         → renderDocsPage(...)
// render404(...)          → render404Page(...)
workerBody = workerBody
  .replace(/\brenderPublic\(/g,  'renderPublicPage(')
  .replace(/\brenderLogin\(/g,   'renderLoginPage(')
  .replace(/\brenderDocs\(/g,    'renderDocsPage(')
  .replace(/\brender404\(/g,     'render404Page(');

// Step 4: The worker.js inlines FONTS as a const for the setup page —
// but css.js also declares FONTS. To avoid duplicate const, remove worker's FONTS.
// (css.js FONTS is the authoritative one and comes first in the bundle)
workerBody = workerBody.replace(/^\/\/ ── FONTS constant.*\nconst FONTS = `[\s\S]*?`;\s*\n/m, '');

workerBody = workerBody.trim();

// ── Assemble final bundle ─────────────────────────────────────────────────
const ts = process.env.SOURCE_DATE_EPOCH
  ? new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString()
  : 'source-controlled';

const bundle = `/**
 * GK Portfolio — Bundled Cloudflare Worker
 * Auto-generated by build.js — DO NOT EDIT DIRECTLY.
 * Edit source files in src/ then re-run: node build.js
 *
 * ═══════════════════════════════════════════════
 * DASHBOARD DEPLOYMENT (no CLI required):
 *
 *   1. Cloudflare Dashboard → Workers & Pages → Create Worker
 *   2. Edit Code → paste THIS entire file → Save & Deploy
 *   3. Workers & Pages → D1 → Create database → name: gk-portfolio-db
 *   4. Worker → Settings → Variables → D1 Database Bindings
 *      → Variable name: DB  → Select your database
 *   5. Worker → Settings → Variables → Add Secret:
 *      ADMIN_SETUP_TOKEN  (any random 32+ char string)
 *   6. Visit https://your-worker.workers.dev/setup?token=YOUR_TOKEN
 *      → Create admin account → database initialized
 *   7. Worker → Triggers → Custom Domains → portfolio.gulshan-kumar.me
 * ═══════════════════════════════════════════════
 *
 * Generated: ${ts}
 */

// ═══════════════════════════════════════════════════════════════════════════
// CSS & FONTS (from src/templates/css.js)
// ═══════════════════════════════════════════════════════════════════════════
${cssBlock}

// ═══════════════════════════════════════════════════════════════════════════
// PUBLIC SITE RENDERER (from src/templates/public.js)
// ═══════════════════════════════════════════════════════════════════════════
${publicBlock}

// ═══════════════════════════════════════════════════════════════════════════
// ADMIN PANEL RENDERER (from src/templates/admin.js)
// ═══════════════════════════════════════════════════════════════════════════
${adminBlock}

// ═══════════════════════════════════════════════════════════════════════════
// DOCS PAGE RENDERER (from src/templates/docs.js)
// ═══════════════════════════════════════════════════════════════════════════
${docsBlock}

// ═══════════════════════════════════════════════════════════════════════════
// WORKER CORE — routing, auth, DB, handlers (from worker.js)
// ═══════════════════════════════════════════════════════════════════════════
${workerBody}
`;

// ── Verify no leftover stubs ──────────────────────────────────────────────
if (/^\/\/ @@STUB_(?:START|END)$/m.test(bundle) || bundle.includes("throw new Error('renderPublic not bundled") || /\brender(?:Public|Login|Docs|404)\(/.test(bundle)) {
  console.error('ERROR: Stub markers or unrewritten renderer calls remain in bundle.');
  process.exit(1);
}

// ── Verify key functions are present ─────────────────────────────────────
const required = ['renderPublicPage', 'renderLoginPage', 'renderAdminPanel', 'renderDocsPage', 'render404Page', 'sanitizeBasicHtml', 'escHtml'];
for (const fn of required) {
  if (!bundle.includes(fn)) {
    console.error(`ERROR: Required function/name "${fn}" not found in bundle.`);
    process.exit(1);
  }
}

fs.writeFileSync(OUT, bundle, 'utf8');
const lines = bundle.split('\n').length;
const kb    = Math.round(fs.statSync(OUT).size / 1024);
console.log(`✓  bundled_worker.js written — ${lines} lines / ${kb} KB`);
console.log(`   Paste bundled_worker.js into Cloudflare Worker editor and deploy.`);
console.log(`   Do NOT paste worker.js — that is the source skeleton only.`);
